create extension if not exists pgcrypto;

create table if not exists public.crm_users (
  id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete set null,
  full_name text not null,
  email text not null unique,
  phone text not null default '',
  role text not null default 'user' check (role in ('admin', 'user')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint crm_users_ctnano_email check (lower(email) ~ '^[^@[:space:]]+@ctnano\.org$')
);

create table if not exists public.companies (
  id bigint generated by default as identity primary key,
  trade_name text not null,
  legal_name text not null default '',
  cnpj text not null default '',
  organization_type text not null default 'Empresa' check (organization_type in ('Empresa', 'Governo', 'Investidor', 'Outras')),
  mapping_date date,
  size text not null default 'Média',
  sector text not null default '',
  uf text not null default '',
  status text not null default 'Ativa',
  responsible_user_id bigint references public.crm_users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists companies_mapping_date_idx on public.companies (mapping_date desc);
create index if not exists companies_trade_name_idx on public.companies (trade_name);

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete restrict,
  name text not null,
  email text not null default '',
  phone text not null default '',
  role text not null default '',
  prospecting_date date,
  source text not null default 'Prospecção ativa',
  responsible_user_id bigint references public.crm_users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists contacts_company_id_idx on public.contacts (company_id);
create index if not exists contacts_prospecting_date_idx on public.contacts (prospecting_date desc);

create table if not exists public.opportunities (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete restrict,
  source_code text not null default '',
  title text not null,
  stage text not null default 'Proposta enviada' check (stage in ('Proposta enviada', 'Negociação', 'Contratada', 'Encerrada')),
  source_status text not null default '',
  loss_reason text not null default '',
  origin text not null default '',
  technical_team text not null default '',
  modality text not null default 'EMBRAPII CG',
  total_value numeric(16,2) not null default 0,
  company_value numeric(16,2) not null default 0,
  economic_value numeric(16,2) not null default 0,
  embrapii_value numeric(16,2) not null default 0,
  probability integer not null default 10 check (probability between 0 and 100),
  owner text not null default '',
  responsible_user_id bigint references public.crm_users(id) on delete set null,
  uf text not null default '',
  proposal_date date,
  sent_date date,
  accepted_date date,
  contract_date date,
  negotiation_days integer not null default 0 check (negotiation_days >= 0),
  contracting_days integer not null default 0 check (contracting_days >= 0),
  next_step text not null default '',
  due_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint opportunity_contract_date_rule check (contract_date is null or stage = 'Contratada')
);
create index if not exists opportunities_company_id_idx on public.opportunities (company_id);
create index if not exists opportunities_sent_date_idx on public.opportunities (sent_date desc);
create index if not exists opportunities_contract_date_idx on public.opportunities (contract_date desc);

create table if not exists public.activities (
  id bigint generated by default as identity primary key,
  opportunity_id bigint references public.opportunities(id) on delete set null,
  company_id bigint references public.companies(id) on delete set null,
  type text not null default 'Tarefa',
  title text not null,
  due_date date,
  owner text not null default '',
  responsible_user_id bigint references public.crm_users(id) on delete set null,
  status text not null default 'Pendente',
  notes text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists activities_due_date_idx on public.activities (due_date);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  opportunity_id bigint references public.opportunities(id) on delete set null,
  company_id bigint not null references public.companies(id) on delete restrict,
  name text not null,
  status text not null default 'Handover',
  start_date date,
  end_date date,
  manager text not null default '',
  responsible_user_id bigint references public.crm_users(id) on delete set null,
  handover_progress integer not null default 0 check (handover_progress between 0 and 100),
  total_value numeric(16,2) not null default 0,
  created_at timestamptz not null default now()
);

