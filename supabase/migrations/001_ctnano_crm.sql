create or replace function public.handle_new_crm_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  normalized_email text := lower(coalesce(new.email, ''));
begin
  if normalized_email !~ '^[^@[:space:]]+@ctnano\.org$' then
    raise exception 'Somente e-mails @ctnano.org podem acessar o CTNano CRM';
  end if;
  insert into public.crm_users (auth_user_id, full_name, email, phone, role, active)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), split_part(normalized_email, '@', 1)),
    normalized_email,
    coalesce(new.raw_user_meta_data ->> 'phone', ''),
    case when normalized_email = 'ricardo.neres@ctnano.org' then 'admin' else 'user' end,
    true
  )
  on conflict (email) do update set
    auth_user_id = excluded.auth_user_id,
    full_name = case when public.crm_users.full_name = '' then excluded.full_name else public.crm_users.full_name end,
    phone = case when public.crm_users.phone = '' then excluded.phone else public.crm_users.phone end,
    role = case when normalized_email = 'ricardo.neres@ctnano.org' then 'admin' else public.crm_users.role end,
    active = true;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_ctnano_crm on auth.users;
create trigger on_auth_user_created_ctnano_crm
  after insert on auth.users
  for each row execute procedure public.handle_new_crm_user();

